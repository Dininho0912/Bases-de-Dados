CREATE TABLE DISTRICTS(
   CODE NUMERIC (2,0) CHECK (CODE >=1 AND CODE <=40),
   NAME VARCHAR (50) NOT NULL,
   REGION VARCHAR(1) DEFAULT ('C') CHECK (REGION in ('C','M','A')),
   PRIMARY KEY (CODE)
);

CREATE TABLE MUNICIPALITIES(
   CODE NUMERIC (4,0),
   NAME VARCHAR (50),
   DISTRICT NUMERIC (2,0),
   PRIMARY KEY (CODE),
   FOREIGN KEY (DISTRICT)
      REFERENCES DISTRICTS (CODE)
         ON DELETE SET NULL
         ON UPDATE CASCADE
);
